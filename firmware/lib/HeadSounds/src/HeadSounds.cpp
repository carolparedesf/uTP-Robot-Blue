#define MELODY(arr) { arr, (uint8_t)(sizeof(arr) / sizeof(arr[0])) }

// El largo de una melodía se guarda en un uint8_t: máximo 255 notas por sonido.
#define CHECK_LEN(arr) static_assert(sizeof(arr) / sizeof(arr[0]) <= 255, #arr " tiene mas de 255 notas")
CHECK_LEN(S_SALUDO); CHECK_LEN(S_POLCA); CHECK_LEN(S_REPROB); CHECK_LEN(S_EXTRA4); CHECK_LEN(S_MODO);

